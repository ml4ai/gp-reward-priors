#!/usr/bin/env python
"""make_repl_selection.py -- the replication's reward-model selection files (handoff §14.83).

The replication re-selects every reward model's hyper-parameters at seed 100 with Study 1's
own procedure: one Bayes sweep per family x variant, Study 1's ranges, metric, run cap and
stopping rule, ONE agent each.  Only the seed changes -- and, so that Study 1's files are
never touched, the base/production config each sweep points at.  For MR, PT and NMR, each
variant, this writes:

  scripts_<fam>/antmaze_<v>_<fam>_antmaze_eval_repl.yaml        the replication base config
      Study 1's production config with the SAME values and a new header.  The header says
      UNSELECTED-BASE, so train_rewards.sh refuses it, and every SWEPT field's line is
      marked PLACEHOLDER (it holds Study 1's winner until the seed-100 winner replaces it),
      so make_production_config.py --set repl rewrites it even when the two agree.
      Written only when absent: once a winner is in, the file is make_production_config's.
  scripts_<fam>/sweep_antmaze_<v>_<fam>_antmaze_eval_repl.yaml  the seed-100 sweep
      Study 1's sweep file with exactly two values changed -- seed 0 -> 100 and config_path
      -> the replication base config -- checked by parsing both.  Regenerated freely: it is
      a pure function of Study 1's sweep file.

Usage (from the gp_reward-priors root):
    /opt/anaconda3/envs/irl/bin/python scripts_bnn/make_repl_selection.py [--write]
    /opt/anaconda3/envs/irl/bin/python scripts_bnn/make_repl_selection.py --selftest
"""
import argparse
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from experiment_conditions import REPL_FAMILIES, REPL_HELDOUT_SEED, VARIANTS  # noqa: E402

SEL_SEED = 0                                   # Study 1's selection seed, in its sweep files


def paths(fam, v):
    d = f"scripts_{fam}"
    return {"cfg": f"{d}/antmaze_{v}_{fam}_antmaze_eval.yaml",
            "sweep": f"{d}/sweep_antmaze_{v}_{fam}_antmaze_eval.yaml",
            "repl_cfg": f"{d}/antmaze_{v}_{fam}_antmaze_eval_repl.yaml",
            "repl_sweep": f"{d}/sweep_antmaze_{v}_{fam}_antmaze_eval_repl.yaml"}


def swept(sweep_doc):
    """The fields a sweep varies: every parameter that is not a fixed `value`."""
    return {k for k, p in sweep_doc["parameters"].items() if "value" not in p}


def repl_config(cfg_text, swept_keys, fam, v):
    lines = cfg_text.split("\n")
    j = next(i for i, ln in enumerate(lines) if ln.strip() and not ln.startswith("#"))
    body = []
    for ln in lines[j:]:
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)(\s*:\s*)([^#]*?)(\s*)(#.*)?$", ln)
        if m and m.group(1) in swept_keys:
            ln = f"{m.group(1)}{m.group(2)}{m.group(3).rstrip()}   # PLACEHOLDER: Study 1's value; the seed-100 sweep selects it"
        body.append(ln)
    header = [
        f"# REPLICATION base config, {fam.upper()} {v} (handoff §14.83).",
        "# GENERATED by scripts_bnn/make_repl_selection.py from Study 1's production config:",
        "# every VALUE is Study 1's; only this header and the PLACEHOLDER marks differ.",
        "# UNSELECTED-BASE: train_rewards.sh refuses this file until",
        "#   scripts_bnn/make_production_config.py --set repl writes the seed-100 winner.",
        "# The seed-100 sweep overrides every PLACEHOLDER field per trial and inherits the",
        "# rest unchanged, exactly as Study 1's seed-0 sweep inherited them.",
        "#",
    ]
    return "\n".join(header + body)


def repl_sweep(sweep_text, p):
    head = ["# GENERATED by scripts_bnn/make_repl_selection.py -- do not hand-edit; regenerate.",
            f"# REPLICATION reward-model selection (handoff §14.83): {p['sweep']} with exactly two",
            f"# values changed: seed {SEL_SEED} -> {REPL_HELDOUT_SEED} (the model seed AND the split seed_{REPL_HELDOUT_SEED}),",
            f"# and config_path -> {p['repl_cfg']}.  Everything else is Study 1's procedure.",
            "#"]
    t, n1 = re.subn(r"(\n  seed:\n    value: )" + str(SEL_SEED) + r"\b", r"\g<1>" + str(REPL_HELDOUT_SEED), sweep_text)
    t, n2 = re.subn(r'(\n  config_path:\n    value: )"?' + re.escape(p["cfg"]) + '"?',
                    r'\g<1>"' + p["repl_cfg"] + '"', t)
    if (n1, n2) != (1, 1):
        raise ValueError(f"{p['sweep']}: expected one seed and one config_path line, found {n1}, {n2}")
    return "\n".join(head) + "\n" + t


def check(p, cfg_text, sweep_text, rc, rs):
    """Problems (list) with a generated pair against its Study 1 sources."""
    probs = []
    a, b = yaml.safe_load(cfg_text), yaml.safe_load(rc)
    if a != b:
        probs.append(f"{p['repl_cfg']}: values differ from {p['cfg']}: "
                     f"{sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))}")
    if "UNSELECTED-BASE" not in rc.split("\n", 8)[3]:
        probs.append(f"{p['repl_cfg']}: no UNSELECTED-BASE in the header")
    s, r = yaml.safe_load(sweep_text), yaml.safe_load(rs)
    sp, rp = s.pop("parameters"), r.pop("parameters")
    if s != r:
        probs.append(f"{p['repl_sweep']}: top-level keys differ")
    diff = {k for k in set(sp) | set(rp) if sp.get(k) != rp.get(k)}
    if diff != {"seed", "config_path"} or rp["seed"] != {"value": REPL_HELDOUT_SEED} \
            or rp["config_path"] != {"value": p["repl_cfg"]}:
        probs.append(f"{p['repl_sweep']}: changed {sorted(diff)}, seed {rp.get('seed')}, "
                     f"config_path {rp.get('config_path')}")
    marked = {m.group(1) for m in re.finditer(r"^(\w+)\s*:.*PLACEHOLDER", rc, re.M)}
    present = {k for k in swept(yaml.safe_load(sweep_text)) if re.search(rf"^{k}\s*:", rc, re.M)}
    if marked != present:
        probs.append(f"{p['repl_cfg']}: PLACEHOLDER on {sorted(marked)}, swept fields present {sorted(present)}")
    return probs


def run(write, root=ROOT, families=REPL_FAMILIES, variants=VARIANTS):
    bad = 0
    for fam in families:
        for v in variants:
            p = paths(fam, v)
            cfg_text = open(os.path.join(root, p["cfg"])).read()
            sweep_text = open(os.path.join(root, p["sweep"])).read()
            rc = repl_config(cfg_text, swept(yaml.safe_load(sweep_text)), fam, v)
            rs = repl_sweep(sweep_text, p)
            probs = check(p, cfg_text, sweep_text, rc, rs)
            for q in probs:
                print(f"  !! {q}")
            bad += bool(probs)
            for key, text, keep in (("repl_cfg", rc, True), ("repl_sweep", rs, False)):
                path = os.path.join(root, p[key])
                old = open(path).read() if os.path.exists(path) else None
                if old == text:
                    st = "unchanged"
                elif old is not None and keep:
                    st = "exists and differs: LEFT ALONE (a winner is in, or it was edited)"
                else:
                    st = ("CHANGED" if old is not None else "new") + \
                        (" (written)" if write and not probs else "")
                    if write and not probs:
                        open(path, "w").write(text)
                print(f"  {p[key]:62s} {st}")
    print("ALL CHECKS PASS" if not bad else f"{bad} pair(s) FAILED: nothing of theirs written")
    return 1 if bad else 0


def selftest():
    import tempfile
    cfg = ("# Production config: round-2 MR BASELINE winner a4qo4g4i\n#\nproject: MR-training\n"
           "width: 7   # log2 exponent; round-2 baseline winner a4qo4g4i (was 8)\ndepth: 4\n"
           "lr: 0.00041   # winner\nepochs: 5000\nseed: 1\n")
    sw = ("project: MR-training\nprogram: run_mr_training_antmaze_eval.py\nmethod: bayes\n"
          "run_cap: 130\nparameters:\n  config_path:\n    value: \"scripts_mr/antmaze_medium_play_mr_antmaze_eval.yaml\"\n"
          "  seed:\n    value: 0\n  epochs:\n    value: 5000\n  width:\n    distribution: int_uniform\n"
          "    min: 4\n    max: 7\n  depth:\n    values: [1, 2, 3, 4]\n  lr:\n    distribution: log_uniform_values\n"
          "    min: 1.0e-5\n    max: 1.0e-2\n")
    with tempfile.TemporaryDirectory() as d:
        os.makedirs(os.path.join(d, "scripts_mr"))
        p = paths("mr", "medium_play")
        open(os.path.join(d, p["cfg"]), "w").write(cfg)
        open(os.path.join(d, p["sweep"]), "w").write(sw)
        assert run(False, d, ("mr",), ("medium_play",)) == 0
        assert not os.path.exists(os.path.join(d, p["repl_cfg"]))           # dry run writes nothing
        assert run(True, d, ("mr",), ("medium_play",)) == 0
        rc = open(os.path.join(d, p["repl_cfg"])).read()
        rs = open(os.path.join(d, p["repl_sweep"])).read()
        assert yaml.safe_load(rc) == yaml.safe_load(cfg) and "UNSELECTED-BASE" in rc
        assert re.findall(r"^(\w+)\s*:.*PLACEHOLDER", rc, re.M) == ["width", "depth", "lr"]
        assert "a4qo4g4i" not in rc                                          # Study 1's provenance is gone
        assert "epochs: 5000\n" in rc                                        # unswept lines untouched
        r = yaml.safe_load(rs)["parameters"]
        assert r["seed"] == {"value": 100} and r["config_path"] == {"value": p["repl_cfg"]}
        # a selected replication config is never overwritten
        open(os.path.join(d, p["repl_cfg"]), "w").write("# Production config ... winner\nwidth: 5\n")
        assert run(True, d, ("mr",), ("medium_play",)) == 0
        assert open(os.path.join(d, p["repl_cfg"])).read().startswith("# Production config")
        # a sweep file without the expected seed line is refused, and nothing is written
        open(os.path.join(d, p["sweep"]), "w").write(sw.replace("value: 0", "value: 3"))
        try:
            run(True, d, ("mr",), ("medium_play",))
            raise AssertionError("seed 3 accepted")
        except ValueError:
            pass
    print("selftest OK")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    return selftest() if a.selftest else run(a.write)


if __name__ == "__main__":
    sys.exit(main())
